/**
 * Phase 27: Evaluation Contracts for Summary Evaluation (SEVAL-01, SEVAL-02)
 *
 * Canonical Zod schemas for summary evaluation cases.
 * Summary evaluation scores groundedness, coverage, and citation adherence
 * for LLM-generated summaries over retrieved context.
 *
 * Key design decisions:
 * - Required facts: Facts that MUST appear in the summary for coverage scoring
 * - Forbidden claims: Claims that MUST NOT appear for hallucination detection
 * - Groundedness threshold: Minimum ratio of supported claims
 * - Coverage threshold: Minimum ratio of required facts covered
 */

import { z } from 'zod';

import { retrievalEvalRequestSchema, retrievalEvalTierSchema } from './retrieval.js';

// =============================================================================
// Summary Eval Endpoint Enum
// =============================================================================

/**
 * Summary evaluation endpoint enum.
 * Summaries can be generated by both v1 and v2 retrieval endpoints.
 */
export const summaryEvalEndpointSchema = z.enum(['/v1/retrieval/search', '/v2/retrieval/search']);

export type SummaryEvalEndpoint = z.infer<typeof summaryEvalEndpointSchema>;

// =============================================================================
// Summary Eval Tier Enum
// =============================================================================

/**
 * Re-export tier schema for summary evaluation consistency.
 * Uses the same tier values as retrieval evaluation.
 */
export const summaryEvalTierSchema = retrievalEvalTierSchema;

export type SummaryEvalTier = z.infer<typeof summaryEvalTierSchema>;

// =============================================================================
// Summary Eval Expected Schema
// =============================================================================

/**
 * Expected outcome schema for summary evaluation cases.
 * Defines the thresholds and constraints for judge-driven verification.
 */
export const summaryEvalExpectedSchema = z.object({
  /** Facts that MUST appear in the summary for coverage scoring */
  requiredFacts: z.array(z.string().min(1)),
  /** Claims that MUST NOT appear in the summary (hallucination detection) */
  forbiddenClaims: z.array(z.string().min(1)),
  /** Minimum threshold for groundedness score (supported claims ratio) */
  minGroundedness: z.number().min(0).max(1).default(0.8),
  /** Minimum threshold for coverage score (required facts coverage) */
  minCoverage: z.number().min(0).max(1).default(0.7),
  /** Whether a summary is expected in the response */
  expectSummary: z.boolean().default(true),
});

export type SummaryEvalExpected = z.infer<typeof summaryEvalExpectedSchema>;

// =============================================================================
// Summary Eval Case Schema
// =============================================================================

/**
 * Canonical case schema for summary evaluation (SEVAL-01, SEVAL-02).
 * Each case targets a specific endpoint and carries required facts and forbidden claims.
 * Cases reference scenarios for fixture state and actor context.
 *
 * Design constraints enforced:
 * - Endpoint must be explicit ('/v1/retrieval/search' or '/v2/retrieval/search')
 * - Required facts and forbidden claims are separate assertion groups
 * - Schema version field supports future contract evolution
 */
export const summaryEvalCaseSchema = z.object({
  /** Schema version for future contract evolution */
  schemaVersion: z.literal(1),
  /** Unique case identifier */
  caseId: z.string().min(1),
  /** Evaluation tier (smoke for fast feedback, core for broader coverage) */
  tier: summaryEvalTierSchema,
  /** Target endpoint (explicit to prevent adapter drift) */
  endpoint: summaryEvalEndpointSchema,
  /** Request to send to the endpoint */
  request: retrievalEvalRequestSchema,
  /** Reference to the scenario providing fixture state and actor context */
  scenarioId: z.string().min(1),
  /** Expected outcomes and assertions */
  expected: summaryEvalExpectedSchema,
  /** Tags for filtering and categorization */
  tags: z.array(z.string()).default([]),
});

export type SummaryEvalCase = z.infer<typeof summaryEvalCaseSchema>;
