#!/usr/bin/env tsx
/**
 * Generate JSON Schema (draft 2020-12) from Zod SSOT.
 *
 * Source: `packages/contracts/src/domain/go-accelerator.ts` (goAcceleratorSchemas)
 * Target: `contracts/json-schema/go-accelerator/*.json`
 *
 * Usage:
 *   pnpm --filter @trapmap/contracts exec tsx scripts/generate-json-schema.ts        # write
 *   pnpm --filter @trapmap/contracts exec tsx scripts/generate-json-schema.ts --check # fail on drift
 *
 * CI gate: `pnpm generate:contracts --check` + `git diff --exit-code` mirrors
 * the OpenAPI drift pattern (hand-crafted spec + generated types + CI check).
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { goAcceleratorSchemas } from '../src/domain/go-accelerator.js';
import { knowledgeReadSchemas } from '../src/domain/knowledge-read-go.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const OUT_DIR = join(ROOT, 'contracts', 'json-schema', 'go-accelerator');
const OUT_DIR_KR = join(ROOT, 'contracts', 'json-schema', 'knowledge-read-go');

type SchemaMap = Record<string, { toJSONSchema: () => unknown }>;

function toSortedJson(value: unknown): string {
  return JSON.stringify(value, null, 2) + '\n';
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const check = args.includes('--check');

  const schemas = goAcceleratorSchemas as unknown as SchemaMap;
  const entries = Object.entries(schemas);
  const schemasKR = knowledgeReadSchemas as unknown as SchemaMap;
  const entriesKR = Object.entries(schemasKR);

  await mkdir(OUT_DIR, { recursive: true });
  await mkdir(OUT_DIR_KR, { recursive: true });

  // Write each schema's JSON Schema
  const generated = new Map<string, string>();
  for (const [name, schema] of entries) {
    const jsonSchema = schema.toJSONSchema() as Record<string, unknown>;
    // Ensure $schema is draft 2020-12 (Zod 4 emits it) and add title
    if (!jsonSchema.$schema) {
      jsonSchema.$schema = 'https://json-schema.org/draft/2020-12/schema';
    }
    // Title helps quicktype/go-jsonschema naming
    if (!jsonSchema.title) {
      jsonSchema.title = name;
    }
    // x-go-type hint for manual mapping (payload -> json.RawMessage)
    const content = toSortedJson(jsonSchema);
    generated.set(name, content);
  }

  // Also write an index that lists all schemas (for humans)
  const indexContent = toSortedJson({
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'go-accelerator-index',
    description:
      'Index of go-accelerator Zod->JSON Schema (contracts SSOT). Generated by packages/contracts/scripts/generate-json-schema.ts — do not edit manually.',
    generatedAt: new Date().toISOString(),
    schemas: Object.fromEntries(entries.map(([k]) => [k, `./${k}.json`])),
  });
  generated.set('_index', indexContent);

  // Knowledge-read-go schemas
  const generatedKR = new Map<string, string>();
  for (const [name, schema] of entriesKR) {
    const jsonSchema = schema.toJSONSchema() as Record<string, unknown>;
    if (!jsonSchema.$schema) jsonSchema.$schema = 'https://json-schema.org/draft/2020-12/schema';
    if (!jsonSchema.title) jsonSchema.title = name;
    generatedKR.set(name, toSortedJson(jsonSchema));
  }
  const indexKR = toSortedJson({
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'knowledge-read-go-index',
    description:
      'Index of knowledge-read-go Zod->JSON Schema. Generated by generate-json-schema.ts — do not edit manually.',
    generatedAt: new Date().toISOString(),
    schemas: Object.fromEntries(entriesKR.map(([k]) => [k, `./${k}.json`])),
  });
  generatedKR.set('_index', indexKR);

  if (check) {
    let drift = false;
    for (const [name, content] of generatedKR) {
      const filePath = join(OUT_DIR_KR, `${name}.json`);
      let existing = '';
      try {
        existing = await readFile(filePath, 'utf8');
      } catch {
        console.error(`[generate:contracts] missing ${filePath} — run without --check to generate`);
        drift = true;
        continue;
      }
      if (name === '_index') {
        const a = JSON.parse(existing) as Record<string, unknown>;
        const b = JSON.parse(content) as Record<string, unknown>;
        const { generatedAt: _a, ...restA } = a as { generatedAt?: unknown };
        const { generatedAt: _b, ...restB } = b as { generatedAt?: unknown };
        if (JSON.stringify(restA) !== JSON.stringify(restB)) {
          console.error(`[generate:contracts] drift in knowledge-read-go/${name}.json`);
          drift = true;
        }
        continue;
      }
      try {
        const ep = JSON.parse(existing);
        const gp = JSON.parse(content);
        if (JSON.stringify(ep) !== JSON.stringify(gp)) {
          console.error(
            `[generate:contracts] drift in knowledge-read-go/${name}.json — run pnpm generate:contracts to regenerate`,
          );
          drift = true;
        }
      } catch {
        console.error(
          `[generate:contracts] drift in knowledge-read-go/${name}.json — run pnpm generate:contracts to regenerate`,
        );
        drift = true;
      }
    }
    for (const [name, content] of generated) {
      const filePath = join(OUT_DIR, `${name}.json`);
      let existing = '';
      try {
        existing = await readFile(filePath, 'utf8');
      } catch {
        console.error(`[generate:contracts] missing ${filePath} — run without --check to generate`);
        drift = true;
        continue;
      }
      // Normalize: compare parsed JSON stringified (ignore generatedAt in index)
      if (name === '_index') {
        const a = JSON.parse(existing) as Record<string, unknown>;
        const b = JSON.parse(content) as Record<string, unknown>;
        // generatedAt is volatile — compare everything else
        const { generatedAt: _a, ...restA } = a as { generatedAt?: unknown };
        const { generatedAt: _b, ...restB } = b as { generatedAt?: unknown };
        if (JSON.stringify(restA) !== JSON.stringify(restB)) {
          console.error(`[generate:contracts] drift in ${name}.json`);
          drift = true;
        }
        continue;
      }
      try {
        const ep = JSON.parse(existing);
        const gp = JSON.parse(content);
        if (JSON.stringify(ep) !== JSON.stringify(gp)) {
          console.error(
            `[generate:contracts] drift in ${name}.json — run pnpm generate:contracts to regenerate`,
          );
          // Show first diff line
          const eLines = existing.split('\n');
          const gLines = content.split('\n');
          for (let i = 0; i < Math.min(eLines.length, gLines.length); i++) {
            if (eLines[i] !== gLines[i]) {
              console.error(
                `  line ${i + 1}: expected ${JSON.stringify(gLines[i])} got ${JSON.stringify(eLines[i])}`,
              );
              break;
            }
          }
          drift = true;
        }
      } catch {
        console.error(
          `[generate:contracts] drift in ${name}.json — run pnpm generate:contracts to regenerate`,
        );
        drift = true;
      }
    }
    if (drift) {
      console.error(
        `\n[generate:contracts] JSON Schema drift detected. Run: pnpm generate:contracts`,
      );
      process.exit(1);
    }
    console.log(`[generate:contracts] check ok — ${generated.size} schemas in sync (${OUT_DIR})`);
    return;
  }

  for (const [name, content] of generatedKR) {
    const filePath = join(OUT_DIR_KR, `${name}.json`);
    await writeFile(filePath, content, 'utf8');
    console.log(`[generate:contracts] wrote ${filePath}`);
  }
  console.log(`[generate:contracts] done — ${generatedKR.size} files in ${OUT_DIR_KR}`);
  for (const [name, content] of generated) {
    const filePath = join(OUT_DIR, `${name}.json`);
    await writeFile(filePath, content, 'utf8');
    console.log(`[generate:contracts] wrote ${filePath}`);
  }
  console.log(`[generate:contracts] done — ${generated.size} files in ${OUT_DIR}`);
}

main().catch((err) => {
  console.error('[generate:contracts] failed', err);
  process.exit(1);
});
